let start = new Date("2023-01-01T08:30:00");
let end = new Date("2025-07-09T10:45:30");

// Step 1: Calculate year and month difference using getFullYear and getMonth
let startYear = start.getFullYear();
let endYear = end.getFullYear();

let startMonth = start.getMonth();
let endMonth = end.getMonth();

let years = endYear - startYear;
let months = endMonth - startMonth;

if (months < 0) {
    years--;
    months += 12;
}

// Step 2: Create adjusted date for days/hours/minutes/seconds calculation
let adjustedStart = new Date(start);
adjustedStart.setFullYear(adjustedStart.getFullYear() + years);
adjustedStart.setMonth(adjustedStart.getMonth() + months);

// Step 3: Remaining time difference in milliseconds
let remainingMs = end - adjustedStart;

// Step 4: Convert to days, hours, minutes, seconds
let totalSeconds = Math.floor(remainingMs / 1000);
let days = Math.floor(totalSeconds / (60 * 60 * 24));
let hours = Math.floor((totalSeconds % (60 * 60 * 24)) / (60 * 60));
let minutes = Math.floor((totalSeconds % (60 * 60)) / 60);
let seconds = totalSeconds % 60;

// Step 5: Final Output
console.log(`Difference: ${years} years, ${months} months, ${days} days, ${hours} hours, ${minutes} minutes, ${seconds} seconds`);

