// 1. 
let start = new Date("2025-01-01T00:00:00");
let end = new Date("2025-01-03T05:30:45");

// 2. Total milliseconds difference
let diffMs = end - start;

// 3. Conversion constants
let msInSecond = 1000;
let msInMinute = msInSecond * 60; // 60,000
let msInHour = msInMinute * 60; // 3,600,000
let msInDay = msInHour * 24; // 86,400,000

// 4. Breakdown of time difference
let days = Math.floor(diffMs / msInDay);
diffMs = diffMs % msInDay;

let hours = Math.floor(diffMs / msInHour);
diffMs = diffMs % msInHour;

let minutes = Math.floor(diffMs / msInMinute);
diffMs = diffMs % msInMinute;

let seconds = Math.floor(diffMs / msInSecond);
let milliseconds = diffMs % msInSecond;

// 5. Output
console.log(`Time Difference: ${ days } :days ${ hours } :hours ${ minutes } :minutes ${ seconds } :seconds ${ milliseconds } :milliseconds `);
