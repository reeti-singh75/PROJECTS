function vowelendstart(a) {
    for (let i = 0; i < a.length; i++) {
        if (a[i] == " ") {
            if (
                (a[i - 1] == "a" || a[i - 1] == "e" || a[i - 1] == "i" || a[i - 1] == "o" || a[i - 1] == "u") &&
                (a[i + 1] == "a" || a[i + 1] == "e" || a[i + 1] == "i" || a[i + 1] == "o" || a[i + 1] == "u")
            ) {
                return true;
            }

        }

    }
    return false;
}


