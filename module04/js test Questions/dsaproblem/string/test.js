// //🧩 Q13. Grade System
// Use switch case to return :
//"Excellent"if marks are 90 +
// "Very Good" for 75– 89
// "Good" for 60– 74
//"Fail otherwise

let marks = 94;
let Grade = " ";
if (marks >= 90) {
    Grade = "Excellent";
    // console.log("Excellent");
} else if (marks >= 75) {
    Grade = "Very Good";
    // console.log("Very Good");
} else if (marks >= 60) {
    Grade = "Good";
    // console.log("Good");
} else {
    Grade = "Fail";
    // console.log("Fail");

}

switch (Grade) {

    case "Excellent":
        console.log("Excellent");
        break;

    case "Very Good":
        console.log("Very Good");
        break;
    case "Good":
        console.log("Good");
        break;
    default:
        console.log("Fail");
}
